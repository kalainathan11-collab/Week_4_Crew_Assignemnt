from crewai import Agent, Task, Crew, Process, LLM
from dotenv import load_dotenv

load_dotenv()

# -----------------------------
# LLM
# -----------------------------
llm = LLM(
    model="gpt-4o-mini",
    temperature=0.2
)

# -----------------------------
# AGENT 1
# -----------------------------
requirement_analyst = Agent(
    role="Requirement Analyst",
    goal="Analyze the requirement and identify test scenarios",
    backstory="You are an experienced QA analyst.",
    llm=llm
)

# -----------------------------
# AGENT 2
# -----------------------------
test_case_writer = Agent(
    role="Test Case Writer",
    goal="Create test cases from the requirement analysis",
    backstory="You are an experienced QA test case designer.",
    llm=llm
)

# -----------------------------
# AGENT 3
# -----------------------------
test_reviewer = Agent(
    role="Test Case Reviewer",
    goal="Review the generated test cases",
    backstory="You are a senior QA lead.",
    llm=llm
)

# ==========================================================
# TASK 1
# ==========================================================

analyze_requirement = Task(
    description="""
    Analyze this requirement:

    User should be able to login using a valid username
    and password.

    Identify:
    - Positive scenarios
    - Negative scenarios
    - Boundary scenarios
    - Validation scenarios
    """,

    expected_output="""
    A list of test scenarios categorized as positive,
    negative, boundary and validation scenarios.
    """,

    agent=requirement_analyst
)

# ==========================================================
# TASK 2
# ==========================================================

generate_test_cases = Task(
    description="""
    Based on the requirement analysis from the previous task,
    generate detailed test cases.

    Include:
    - Test Case ID
    - Scenario
    - Steps
    - Expected Result
    - Priority
    """,

    expected_output="""
    A complete list of executable QA test cases.
    """,

    agent=test_case_writer,

    # IMPORTANT:
    # Task 2 receives output from Task 1
    context=[analyze_requirement]
)

# ==========================================================
# TASK 3
# ==========================================================

review_test_cases = Task(
    description="""
    Review the test cases generated by the previous task.

    Check:
    - Missing scenarios
    - Duplicate cases
    - Incorrect expected results
    - Missing negative scenarios
    - Missing boundary scenarios

    Provide the corrected final test cases.
    """,

    expected_output="""
    Reviewed and corrected final QA test cases.
    """,

    agent=test_reviewer,

    # Task 3 receives output from Task 2
    context=[generate_test_cases]
)

# ==========================================================
# CREW
# ==========================================================

crew = Crew(
    agents=[
        requirement_analyst,
        test_case_writer,
        test_reviewer
    ],

    tasks=[
        analyze_requirement,
        generate_test_cases,
        review_test_cases
    ],

    # THIS IS THE PROCESS
   process=Process.sequential,
    #process=Process.hierarchical,
    

    verbose=True
)

# ==========================================================
# EXECUTE PROCESS
# ==========================================================

result = crew.kickoff()

# ==========================================================
# FINAL OUTPUT
# ==========================================================

print("\n====================================")
print("FINAL RESULT")
print("====================================")

print(result)